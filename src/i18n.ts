export function translate(locale: Locale, key: Key): string {
  if (key in interactionMessages.en)
    return interactionMessages[locale][
      key as keyof typeof interactionMessages.en
    ];
  if (key in menuMessages.en)
    return menuMessages[locale][key as keyof typeof menuMessages.en];
  if (key in workspaceMessages.en)
    return workspaceMessages[locale][key as keyof typeof workspaceMessages.en];
  if (key in associationMessages.en)
    return associationMessages[locale][
      key as keyof typeof associationMessages.en
    ];
  const index = keys.indexOf(key as BaseKey);
  return values[locale]?.[index] || values.en[index] || key;
}

